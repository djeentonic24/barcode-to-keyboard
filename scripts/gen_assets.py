#!/usr/bin/env python3
"""Generate firmware headers from host/payload.py (PDF417 bitmap + SAMPLE bytes)."""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from host.payload import SAMPLE, AAMVA_FIELDS, selfcheck  # noqa: E402


def c_bytes(data: bytes, name: str) -> str:
    lines = [f"static const uint8_t {name}[] = {{"]
    chunk = []
    for b in data:
        chunk.append(f"0x{b:02X}")
        if len(chunk) == 12:
            lines.append("    " + ", ".join(chunk) + ",")
            chunk = []
    if chunk:
        lines.append("    " + ", ".join(chunk) + ",")
    lines.append("};")
    return "\n".join(lines)


def pack_bitmap(bits_rows: list[list[int]]) -> tuple[int, int, bytes]:
    h = len(bits_rows)
    w = len(bits_rows[0])
    stride = (w + 7) // 8
    out = bytearray(stride * h)
    for y, row in enumerate(bits_rows):
        for x, bit in enumerate(row):
            if bit:
                out[y * stride + (x >> 3)] |= 0x80 >> (x & 7)
    return w, h, bytes(out)


def pdf417_matrix(data: bytes) -> list[list[int]]:
    from pdf417gen import encode, render_image

    codes = encode(data.decode("latin1"), columns=6, security_level=2)
    img = render_image(codes, scale=1, ratio=1, padding=0).convert("1")
    px = img.load()
    w, h = img.size
    # PIL mode 1: 0 = black (bar), 255 = white
    return [[1 if px[x, y] == 0 else 0 for x in range(w)] for y in range(h)]


def main() -> None:
    selfcheck()
    dest = ROOT / "firmware" / "esp_scanner"
    dest.mkdir(parents=True, exist_ok=True)

    (dest / "aamva_payload.h").write_text(
        "#pragma once\n"
        "// Generated by scripts/gen_assets.py — do not edit.\n"
        f"// {len(SAMPLE)} bytes, DAC={AAMVA_FIELDS['DAC']} "
        f"DCS={AAMVA_FIELDS['DCS']} DAQ={AAMVA_FIELDS['DAQ']}\n\n"
        f"{c_bytes(SAMPLE, 'AAMVA_PAYLOAD')}\n"
        f"static const unsigned AAMVA_PAYLOAD_LEN = sizeof(AAMVA_PAYLOAD);\n",
        encoding="utf-8",
    )

    matrix = pdf417_matrix(SAMPLE)
    w, h, packed = pack_bitmap(matrix)
    (dest / "pdf417_bitmap.h").write_text(
        "#pragma once\n"
        "// Generated PDF417 of AAMVA_PAYLOAD (pdf417gen, columns=6, ECL=2).\n"
        f"static const int PDF417_WIDTH = {w};\n"
        f"static const int PDF417_HEIGHT = {h};\n"
        f"static const int PDF417_STRIDE = {(w + 7) // 8};\n"
        f"{c_bytes(packed, 'PDF417_BITS')}\n",
        encoding="utf-8",
    )
    print(f"wrote payload {len(SAMPLE)} B, PDF417 {w}x{h} -> {dest}")


if __name__ == "__main__":
    main()
